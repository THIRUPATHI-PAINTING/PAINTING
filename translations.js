let currentLang = localStorage.getItem('lang') || 'en';
const originalTexts = new Map();

function translatePage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    
    // Update active button state
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if(btn.dataset.lang === lang) btn.classList.add('active');
    });

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    let node;
    while(node = walker.nextNode()) {
        const text = node.nodeValue.trim();
        if(node.parentElement && (node.parentElement.tagName === 'SCRIPT' || node.parentElement.tagName === 'STYLE')) continue;
        
        if(text.length > 0) {
            if(!originalTexts.has(node)) {
                originalTexts.set(node, node.nodeValue);
            }
            
            let originalText = originalTexts.get(node).trim();
            if(lang === 'ta' && dictionary[originalText]) {
                node.nodeValue = originalTexts.get(node).replace(originalText, dictionary[originalText]);
            } else if(lang === 'en') {
                node.nodeValue = originalTexts.get(node);
            }
        }
    }
    
    const inputs = document.querySelectorAll('input[placeholder]');
    inputs.forEach(input => {
        if(!originalTexts.has(input)) {
            originalTexts.set(input, input.placeholder);
        }
        let originalText = originalTexts.get(input).trim();
        if(lang === 'ta' && dictionary[originalText]) {
            input.placeholder = dictionary[originalText];
        } else if(lang === 'en') {
            input.placeholder = originalTexts.get(input);
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            translatePage(e.target.dataset.lang);
        });
    });
    
    if(currentLang === 'ta') {
        translatePage('ta');
    }
});
